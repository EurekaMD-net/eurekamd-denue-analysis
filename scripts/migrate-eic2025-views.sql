-- eic_2025_municipio_censo_parity: absolutes named like the Censo 2020
-- municipal columns the API reads. Direct counts are EIC absolutes; derived
-- ones are PCN_X x base / 100, rounded, with the base INEGI publishes for each
-- percentage (brief §3): VIVPARHAB_C for vph_*, PDER_SS for the institution
-- shares, P_12YMAS for pea / p12ym_*, P_15YMAS for p15ym_*, P_3YMAS for
-- p3ym_hli, indigenous-language speakers (unrounded) for p3hlinhe / p3hli_he,
-- P_5YMAS for the 2020 residence columns (named pres2020 / presoe20: EIC asks
-- about October 2020, not 2015), POBTOT otherwise. tvivhab = VIVPARHAB
-- (private inhabited dwellings only); pder_segp approximates with
-- PCN_PAFIL_IPUB. No equivalent in EIC: p_18ymas, tvivpar, religion,
-- p15pri_* / p15sec_*, p18ym_pb, vph_spmvpi / vph_cvj / vph_snbien.
CREATE OR REPLACE VIEW eic_2025_municipio_censo_parity AS
SELECT
  e.cve_mun,
  e.cve_ent AS entidad,
  e.mun,
  e.nom_ent,
  e.nom_mun,
  e.enumeracion_completa,
  e.muestra_insuficiente,
  round(e.pobtot)::bigint AS pobtot,
  round(e.pobfem)::bigint AS pobfem,
  round(e.pobmas)::bigint AS pobmas,
  round(e.p_12ymas)::bigint AS p_12ymas,
  round(e.p_15ymas)::bigint AS p_15ymas,
  round((e.pcn_p_60a64 + e.pcn_p_65a69 + e.pcn_p_70a74 + e.pcn_p_75ymas) * e.pobtot / 100)::bigint AS p_60ymas,
  round(e.pcn_pea * e.p_12ymas / 100)::bigint AS pea,
  round(e.pocupada)::bigint AS pocupada,
  e.graproes AS graproes,
  round(e.vivparhab)::bigint AS tvivhab,
  round(e.pcn_p3ym_hli * e.p_3ymas / 100)::bigint AS p3ym_hli,
