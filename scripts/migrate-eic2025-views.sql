-- EIC 2025 (INEGI Encuesta Intercensal 2025) municipal views over
-- eic_2025_municipio_raw. Canonical DDL: scripts/load-eic2025.ts drops the
-- three views explicitly, swaps the raw table in and re-runs this file inside
-- its single load transaction (docs/EIC-2025-LOADER-BRIEF-2026-09-28.md §4).
--
-- Rules for this file (scripts/load-eic2025.test.ts pins them):
--   * No BEGIN/COMMIT and no psql meta-commands: it runs inside the loader's
--     transaction, piped over stdin.
--   * The views read ONLY eic_2025_municipio_raw (and each other). They must
--     never depend on the 2025 municipio universe view, the 2020 -> 2025
--     bridge table or any Censo 2020 relation: the Censo loader drops those
--     without CASCADE, so a dependent view here would break every Censo
--     reload. Join them in the handlers instead.
--   * Estimates come from a sample survey of private dwellings: POBTOT is
--     "Población en viviendas particulares habitadas", not the census total.
--
-- Municipio rows: cve_loc = '0000' AND mun NOT IN ('000', '997') (2,478
-- units). NOM_MUN suffixes: '*' = fully enumerated municipio (750), '**' =
-- sample too small, most indicators 'MI' (7). Sentinels 'MI' (insufficient
-- sample) and 'NA' (zero denominator) become NULL; any other non-numeric
-- value fails the cast and rolls the load back.

